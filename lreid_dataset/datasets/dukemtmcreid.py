from __future__ import division, print_function, absolute_import
import collections
import os
import copy
import os.path as osp
from lreid_dataset.incremental_datasets import IncrementalPersonReIDSamples
from lreid_dataset.data.dataset import ImageDataset
import re
import glob

cam_num = 8
class IncrementalSamples4duke(IncrementalPersonReIDSamples):
    '''
    Duke dataset
    '''
    duke_path = ''
    def __init__(self, datasets_root, cam_filter, relabel=True, combineall=False):
        # 初始化方法，设置根目录、是否重新标记 ID 以及是否合并所有数据
        self.global_pid2lable={}
        self.next_pid_lable = 0
        self.relabel = relabel  # 是否重新标记 ID
        self.combineall = combineall  # 是否合并所有训练数据（包括查询和库）
        root = osp.join(datasets_root, self.duke_path,'DukeMTMC-reID')

        self.train_dir = osp.join(
            root, 'bounding_box_train'
        )
        self.query_dir = osp.join(root, 'query')
        self.gallery_dir = osp.join(
            root, 'bounding_box_test'
        )
        self.check_before_run()
        self.get_global_lable(self.train_dir) # 按照顺序建立全局pid-lable映射

        train, cam_num_classes = self.process_cam_dir(self.train_dir, cam_filter)  # 处理训练集，并重新标记 ID
        query = self.process_dir(self.query_dir, cam_filter, relabel=False)
        gallery = self.process_dir(self.gallery_dir, relabel=False)
        self.train, self.query, self.gallery, self.num_classes = train, query, gallery, cam_num_classes
        self._show_info(train, query, gallery)

    def check_before_run(self):
        """Check if all files are available before going deeper"""
        if not osp.exists(self.train_dir):
            raise RuntimeError("'{}' is not available".format(self.train_dir))
        if not osp.exists(self.query_dir):
            raise RuntimeError("'{}' is not available".format(self.query_dir))
        if not osp.exists(self.gallery_dir):
            raise RuntimeError("'{}' is not available".format(self.gallery_dir))

    def get_global_lable(self,train_dir):
        img_paths = sorted(glob.glob(osp.join(train_dir,'*.jpg')))
        pattern = re.compile(r'([-\d]+)_c(\d+)')
        for cam_idx in range(cam_num):
            for img_path in img_paths:
                pid,camid = map(int,pattern.search(img_path).groups())
                if pid < 0:
                    continue
                camid -= 1
                if camid != cam_idx:
                    continue
                if pid not in self.global_pid2lable:
                    self.global_pid2lable[pid] = self.next_pid_lable
                    self.next_pid_lable += 1
    
    def process_dir(self, dir_path, cam_filter=None, relabel=False):
        # 处理数据集文件夹中的图像，并返回包含图像路径、行人 ID 和摄像头 ID 的列表
        img_paths = sorted(glob.glob(osp.join(dir_path, '*.jpg')))  # 获取文件夹中所有图片的路径
        pattern = re.compile(r'([-\d]+)_c(\d+)')  # 定义用于提取行人 ID 和摄像头 ID 的正则表达式
        data = []  # 用于存储处理后的图像数据
        for img_path in img_paths:
            pid, camid = map(int, pattern.search(img_path).groups())  # 提取图片的行人 ID 和摄像头 ID
            if pid < 0:
                continue
            camid -= 1
            if cam_filter is not None :
                if camid == cam_filter:
                    data.append((img_path, pid, camid, 0))
            else:
                data.append((img_path, pid, camid, 0))
                
        return data

    def process_cam_dir(self, dir_path, cam_filter=None):
        img_paths = sorted(glob.glob(osp.join(dir_path, '*.jpg')))  # 获取文件夹中所有图片的路径
        pattern = re.compile(r'([-\d]+)_c(\d+)')  # 定义用于提取行人 ID 和摄像头 ID 的正则表达式

        datasets = collections.defaultdict(list)
        cam_num_classes = [] # 统计每个相机的类别数

        for cam_idx in range(cam_num):
            dataset = []
            pids = set()
            for img_path in img_paths:
                pid, camid = map(int, pattern.search(img_path).groups())
                if pid < 0:
                    continue  # junk images are just ignored
                camid -= 1  # index starts from 0
                if camid!=cam_idx:
                    continue
                pid = self.global_pid2lable[pid]

                dataset.append((img_path, pid, camid, 0))
                pids.add(pid)

            datasets[cam_idx] = dataset
            cam_num_classes.append(len(pids))

        return datasets[cam_filter],cam_num_classes[cam_filter]




class DukeMTMCreID(ImageDataset):
    """DukeMTMC-reID.

    Reference:
        - Ristani et al. Performance Measures and a Data Set for Multi-Target, Multi-Camera Tracking. ECCVW 2016.
        - Zheng et al. Unlabeled Samples Generated by GAN Improve the Person Re-identification Baseline in vitro. ICCV 2017.

    URL: `<https://github.com/layumi/DukeMTMC-reID_evaluation>`_
    
    Dataset statistics:
        - identities: 1404 (train + query).
        - images:16522 (train) + 2228 (query) + 17661 (gallery).
        - cameras: 8.
    """
    dataset_dir = 'dukemtmc-reid'
    dataset_url = 'http://vision.cs.duke.edu/DukeMTMC/data/misc/DukeMTMC-reID.zip'

    def __init__(self, root='', **kwargs):
        self.root = osp.abspath(osp.expanduser(root))
        self.dataset_dir = osp.join(self.root, self.dataset_dir)
        self.download_dataset(self.dataset_dir, self.dataset_url)
        self.train_dir = osp.join(
            self.dataset_dir, 'DukeMTMC-reID/bounding_box_train'
        )
        self.query_dir = osp.join(self.dataset_dir, 'DukeMTMC-reID/query')
        self.gallery_dir = osp.join(
            self.dataset_dir, 'DukeMTMC-reID/bounding_box_test'
        )

        required_files = [
            self.dataset_dir, self.train_dir, self.query_dir, self.gallery_dir
        ]
        self.check_before_run(required_files)

        train = self.process_dir(self.train_dir, relabel=True)
        query = self.process_dir(self.query_dir, relabel=False)
        gallery = self.process_dir(self.gallery_dir, relabel=False)

        super(DukeMTMCreID, self).__init__(train, query, gallery, **kwargs)

    def process_dir(self, dir_path, relabel=False):
        img_paths = glob.glob(osp.join(dir_path, '*.jpg'))
        pattern = re.compile(r'([-\d]+)_c(\d)')

        pid_container = set()
        for img_path in img_paths:
            pid, _ = map(int, pattern.search(img_path).groups())
            pid_container.add(pid)
        pid2label = {pid: label for label, pid in enumerate(pid_container)}

        data = []
        for img_path in img_paths:
            pid, camid = map(int, pattern.search(img_path).groups())
            assert 1 <= camid <= 8
            camid -= 1 # index starts from 0
            if relabel:
                pid = pid2label[pid]
            data.append((img_path, pid, camid, 1))

        return data
